"""E3: what does pypylon do with the GIL, and is zero-copy capture real?

Source-reading answer (pypylon 26.4.1, SWIG 4.3, built with `-threads`):
every wrapped C++ method releases the GIL for the duration of the call EXCEPT the
handful marked `%nothread` -- which includes `GetImageBuffer`, the function that
`result.Array` actually calls, and which copies the whole 2.3 MB frame into a Python
bytearray while HOLDING the GIL. This probe measures that claim instead of trusting it.

INSTRUMENT
A pure-Python competitor thread increments a counter in a tight loop; that is GIL-held
work, so its throughput is a direct meter of how much of the wall clock the measured
thread spends holding the GIL. Over a window W in which the measured thread holds the
GIL for a total of H seconds, the competitor runs for W-H, so

    H = W * (1 - rate_during / rate_solo)

Per-op GIL-held time is the difference between a case and the bare retrieve/release
baseline, divided by the op count. Wall time comes from perf_counter, and Windows
QueryThreadCycleTime gives the cycles the measured thread actually executed, so
wall/exec/GIL-held are three independent numbers per op.

CONTROLS (must behave or nothing else can be believed)
    sleep   -- time.sleep, releases the GIL  -> measured GIL-held must be ~0
    pyspin  -- pure-Python loop, holds it    -> measured GIL-held must be ~= wall

CAMERAS
Uses the pylon camera EMULATOR (PYLON_CAMEMU), configured 1920x1200 Mono8 like the
a2A1920-165g5m, so no rig hardware is touched and the real cameras are never opened.
The GIL wrapper under test is generated by SWIG and is identical for every transport.

    uv run tools/experiments/probe_pypylon_gil.py            # attribution (phase 1)
    uv run tools/experiments/probe_pypylon_gil.py --cams 9   # 9-thread loop comparison (phase 2)
"""
import argparse
import ctypes
import json
import os
import sys
import threading
import time
from pathlib import Path

N_EMU = int(os.environ.get("PROBE_EMU_CAMS", "9"))
os.environ["PYLON_CAMEMU"] = str(N_EMU)

import numpy as np
from pypylon import pylon

W, H = 1920, 1200
EMU_FPS = 1500.0          # keep the output queue full so RetrieveResult never blocks

_k32 = ctypes.WinDLL("kernel32", use_last_error=True)
_k32.QueryThreadCycleTime.argtypes = [ctypes.c_void_p, ctypes.POINTER(ctypes.c_ulonglong)]
_k32.QueryThreadCycleTime.restype = ctypes.c_int


def thread_cycles(_buf=None):
    buf = ctypes.c_ulonglong()
    if not _k32.QueryThreadCycleTime(ctypes.c_void_p(-2), ctypes.byref(buf)):
        raise ctypes.WinError(ctypes.get_last_error())
    return buf.value


def calibrate_cycles_per_s(dur=0.25):
    c0, t0 = thread_cycles(), time.perf_counter()
    x = 0
    while time.perf_counter() - t0 < dur:
        x += 1
    return (thread_cycles() - c0) / (time.perf_counter() - t0)


class Competitor(threading.Thread):
    """Pure-Python GIL-held work; its counter is the GIL availability meter."""

    def __init__(self):
        super().__init__(daemon=True, name="competitor")
        self.n = 0
        self._run = True

    def run(self):
        n = 0
        while self._run:
            n += 1
            if n % 4096 == 0:
                self.n = n
        self.n = n

    def stop(self):
        self._run = False


def make_emu_camera(index, fps=100.0):
    tlf = pylon.TlFactory.GetInstance()
    emu = [d for d in tlf.EnumerateDevices()
           if d.GetDeviceClass() == "BaslerCamEmu"]
    if len(emu) <= index:
        raise RuntimeError(f"need {index + 1} emulated cameras, found {len(emu)}")
    cam = pylon.InstantCamera(tlf.CreateDevice(emu[index]))
    cam.Open()
    cam.Width.SetValue(W)
    cam.Height.SetValue(H)
    cam.PixelFormat.SetValue("Mono8")
    cam.AcquisitionFrameRateAbs.SetValue(fps)
    cam.MaxNumBuffer.SetValue(64)
    return cam


# ---------------------------------------------------------------- phase 1 ----

def calibrated_spin(target_s, cps):
    n = max(1, int(target_s * cps / 6))     # ~6 cycles per trivial loop iteration

    def op(r, nv12):
        x = 0
        for _ in range(n):
            x += 1
    return op


def op_noop(r, nv12):
    pass


def op_sleep(r, nv12):
    time.sleep(0.0005)


def op_getters(r, nv12):
    r.GrabSucceeded()
    r.BlockID
    r.TimeStamp


def op_array(r, nv12):
    r.Array


def op_array_nv12(r, nv12):
    """Exactly what GrabThread's frame access and release do today."""
    img = r.Array
    nv12[:H, :] = img


def op_zerocopy_nv12(r, nv12):
    with r.GetArrayZeroCopy() as z:
        nv12[:H, :] = z


def op_memview_nv12(r, nv12):
    """Leaner than GetArrayZeroCopy: no contextmanager, no refcount guard."""
    mv = r.GetImageMemoryView()
    nv12[:H, :] = np.frombuffer(mv, dtype=np.uint8).reshape(H, W)
    mv.release()


def measure(cam, op, iters, nv12, cps, comp, solo_rate):
    """Run [retrieve, op, release] `iters` times; return wall/exec/gil per iter."""
    # warm up
    for _ in range(20):
        r = cam.RetrieveResult(2000, pylon.TimeoutHandling_ThrowException)
        op(r, nv12)
        r.Release()

    n0, c0, t0 = comp.n, thread_cycles(), time.perf_counter()
    for _ in range(iters):
        r = cam.RetrieveResult(2000, pylon.TimeoutHandling_ThrowException)
        op(r, nv12)
        r.Release()
    wall = time.perf_counter() - t0
    cyc = thread_cycles() - c0
    comp_rate = (comp.n - n0) / wall
    held = wall * max(0.0, 1.0 - comp_rate / solo_rate)
    return dict(wall_ms=wall / iters * 1e3,
                exec_ms=cyc / cps / iters * 1e3,
                gil_ms=held / iters * 1e3,
                comp_frac=comp_rate / solo_rate)


def phase1(iters, switch_intervals):
    cps = calibrate_cycles_per_s()
    print(f"# QueryThreadCycleTime calibration: {cps / 1e9:.3f} Gcycles/s")
    cam = make_emu_camera(0, EMU_FPS)
    print(f"# emulated camera {W}x{H} Mono8, PayloadSize={cam.PayloadSize.GetValue()}, "
          f"free-run {EMU_FPS:g} fps (output queue stays full, so RetrieveResult "
          f"never blocks and every ms measured is host-side work)")
    nv12 = np.full((H * 3 // 2, W), 128, np.uint8)
    cam.StartGrabbing(pylon.GrabStrategy_OneByOne)

    comp = Competitor()
    comp.start()
    time.sleep(0.05)

    out = {}
    for si in switch_intervals:
        sys.setswitchinterval(si)
        # solo competitor rate: measured thread parked in a GIL-free sleep
        n0, t0 = comp.n, time.perf_counter()
        time.sleep(0.5)
        solo_rate = (comp.n - n0) / (time.perf_counter() - t0)

        cases = [
            ("baseline (retrieve+release)", op_noop),
            ("control sleep 0.5 ms", op_sleep),
            ("control pyspin 0.5 ms", calibrated_spin(5e-4, cps)),
            ("getters: GrabSucceeded+BlockID+TimeStamp", op_getters),
            ("r.Array", op_array),
            ("PRODUCTION r.Array + copy to NV12", op_array_nv12),
            ("GetArrayZeroCopy + copy to NV12", op_zerocopy_nv12),
            ("GetImageMemoryView + copy to NV12", op_memview_nv12),
        ]
        rows = {}
        base = None
        print(f"\n## switchinterval = {si * 1e3:g} ms   "
              f"(solo competitor {solo_rate / 1e6:.2f} Mops/s)")
        print(f"{'case':44s} {'wall':>8s} {'exec':>8s} {'GIL-held':>9s} "
              f"{'d_wall':>8s} {'d_GIL':>8s}")
        for name, op in cases:
            m = measure(cam, op, iters, nv12, cps, comp, solo_rate)
            if base is None:
                base = m
                dw = dg = 0.0
            else:
                dw = m["wall_ms"] - base["wall_ms"]
                dg = m["gil_ms"] - base["gil_ms"]
            m["d_wall_ms"], m["d_gil_ms"] = dw, dg
            rows[name] = m
            print(f"{name:44s} {m['wall_ms']:7.3f}m {m['exec_ms']:7.3f}m "
                  f"{m['gil_ms']:8.3f}m {dw:7.3f}m {dg:7.3f}m")
        out[f"switchinterval_{si}"] = rows

    sys.setswitchinterval(0.005)
    comp.stop()
    cam.StopGrabbing()
    cam.Close()
    return out


# ---------------------------------------------------------------- phase 2 ----

class GrabWorker(threading.Thread):
    def __init__(self, index, mode, frames, barrier):
        super().__init__(daemon=True, name=f"grab{index}")
        self.index, self.mode, self.frames, self.barrier = index, mode, frames, barrier
        self.res = {}

    def run(self):
        cam = make_emu_camera(self.index, 100.0)
        nv12_ring = [np.full((H * 3 // 2, W), 128, np.uint8) for _ in range(300)]
        ring_i = 0
        cam.StartGrabbing(pylon.GrabStrategy_OneByOne)
        for _ in range(30):
            r = cam.RetrieveResult(5000, pylon.TimeoutHandling_ThrowException)
            r.Release()
        self.barrier.wait()
        c0, t0 = thread_cycles(), time.perf_counter()
        t_prev, cyc_sum, worst = None, 0, 0.0
        cycles = []
        for _ in range(self.frames):
            ts = time.perf_counter()
            r = cam.RetrieveResult(5000, pylon.TimeoutHandling_ThrowException)
            t1 = time.perf_counter()
            buf = nv12_ring[ring_i]
            ring_i = (ring_i + 1) % len(nv12_ring)
            if self.mode == "production":
                img = r.Array
                buf[:H, :] = img
            else:
                with r.GetArrayZeroCopy() as z:
                    buf[:H, :] = z
            r.BlockID
            r.TimeStamp
            r.Release()
            te = time.perf_counter()
            cycles.append((t1 - ts, te - t1))
            if t_prev is not None:
                worst = max(worst, ts - t_prev)
            t_prev = ts
        wall = time.perf_counter() - t0
        cyc = thread_cycles() - c0
        waits = np.array([c[0] for c in cycles]) * 1e3
        works = np.array([c[1] for c in cycles]) * 1e3
        self.res = dict(
            mode=self.mode, fps=self.frames / wall,
            work_ms_med=float(np.median(works)), work_ms_p99=float(np.percentile(works, 99)),
            wait_ms_med=float(np.median(waits)),
            cycle_ms=(wall / self.frames) * 1e3,
            worst_gap_ms=worst * 1e3,
            exec_ms_per_frame=cyc / CPS / self.frames * 1e3,
            ready_buffers=int(cam.NumReadyBuffers.GetValue()),
        )
        cam.StopGrabbing()
        cam.Close()


CPS = 1.0


def phase2(n_cams, frames):
    global CPS
    CPS = calibrate_cycles_per_s()
    out = {}
    for mode in ("production", "zerocopy"):
        barrier = threading.Barrier(n_cams)
        ws = [GrabWorker(i, mode, frames, barrier) for i in range(n_cams)]
        for w in ws:
            w.start()
        for w in ws:
            w.join()
        rs = [w.res for w in ws if w.res]
        print(f"\n## {mode}: {n_cams} cameras x {frames} frames @100 fps")
        print(f"{'cam':>4s} {'fps':>7s} {'work_ms':>8s} {'p99':>7s} "
              f"{'exec_ms':>8s} {'ready':>6s} {'worst_gap':>10s}")
        for i, r in enumerate(rs):
            print(f"{i:4d} {r['fps']:7.2f} {r['work_ms_med']:8.3f} "
                  f"{r['work_ms_p99']:7.3f} {r['exec_ms_per_frame']:8.3f} "
                  f"{r['ready_buffers']:6d} {r['worst_gap_ms']:10.2f}")
        print(f"  median work/frame across cams: "
              f"{np.median([r['work_ms_med'] for r in rs]):.3f} ms   "
              f"p99 {np.median([r['work_ms_p99'] for r in rs]):.3f} ms")
        out[mode] = rs
        time.sleep(1.0)
    return out


# ---------------------------------------------------------------- phase 0 ----

def phase0(seconds=6.0):
    """Does RetrieveResult release the GIL while BLOCKING? Unambiguous version.

    One thread blocks in RetrieveResult on a 100 fps camera, i.e. it is inside the
    pypylon call ~95% of the wall clock. A pure-Python competitor counts alongside.
    If the GIL were held across the block, the competitor would make ~no progress.
    """
    cps = calibrate_cycles_per_s()
    comp = Competitor()
    comp.start()
    time.sleep(0.05)

    n0, t0 = comp.n, time.perf_counter()
    time.sleep(seconds / 3)
    solo = (comp.n - n0) / (time.perf_counter() - t0)

    cam = make_emu_camera(0, 100.0)
    cam.StartGrabbing(pylon.GrabStrategy_OneByOne)
    for _ in range(10):
        cam.RetrieveResult(2000, pylon.TimeoutHandling_ThrowException).Release()

    rows = {}
    for name, body in (
        ("blocked in RetrieveResult (100 fps camera)", "retrieve"),
        ("same loop + r.Array per frame", "array"),
        ("same loop + GetArrayZeroCopy per frame", "zerocopy"),
        ("reference: pure-Python spin instead of grabbing", "spin"),
    ):
        nv12 = np.full((H * 3 // 2, W), 128, np.uint8)
        n0, c0, t0, frames = comp.n, thread_cycles(), time.perf_counter(), 0
        while time.perf_counter() - t0 < seconds / 3:
            if body == "spin":
                x = 0
                for _ in range(300000):
                    x += 1
                frames += 1
                continue
            r = cam.RetrieveResult(2000, pylon.TimeoutHandling_ThrowException)
            if body == "array":
                nv12[:H, :] = r.Array
            elif body == "zerocopy":
                with r.GetArrayZeroCopy() as z:
                    nv12[:H, :] = z
            r.Release()
            frames += 1
        wall = time.perf_counter() - t0
        rate = (comp.n - n0) / wall
        exec_ms = (thread_cycles() - c0) / cps / frames * 1e3
        rows[name] = dict(comp_frac=rate / solo, fps=frames / wall,
                          exec_ms_per_frame=exec_ms,
                          gil_held_ms_per_frame=(1 - rate / solo) * wall / frames * 1e3)
        print(f"{name:48s} competitor {rate / solo * 100:5.1f}% of solo   "
              f"{frames / wall:6.1f} fps   exec {exec_ms:5.3f} ms/frame   "
              f"GIL-held {rows[name]['gil_held_ms_per_frame']:5.3f} ms/frame")
    comp.stop()
    cam.StopGrabbing()
    cam.Close()
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase0", action="store_true")
    ap.add_argument("--iters", type=int, default=1500)
    ap.add_argument("--cams", type=int, default=0,
                    help="run phase 2 with this many emulated cameras")
    ap.add_argument("--frames", type=int, default=1200)
    a = ap.parse_args()

    res = {}
    if a.phase0:
        res["phase0"] = phase0()
    elif a.cams:
        res["phase2"] = phase2(a.cams, a.frames)
    else:
        res["phase1"] = phase1(a.iters, [0.005, 0.0005])
    outdir = Path(__file__).resolve().parents[2] / "probe_out"
    outdir.mkdir(exist_ok=True)
    p = outdir / ("pypylon_gil_phase0.json" if a.phase0 else ("pypylon_gil.json" if not a.cams else "pypylon_gil_loop.json"))
    p.write_text(json.dumps(res, indent=1))
    print(f"\nwrote {p}")


if __name__ == "__main__":
    main()
